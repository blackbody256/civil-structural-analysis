import {
  chip, downloadBlob, el, fmt, guideHref, KEYS, SEVERITY, STATUS_LABEL, store, utilBar, verdictText, worst,
} from "./common.js";
import { drawElevation, drawInteraction, drawSection, endKinds } from "./drawings.js";

const root = document.getElementById("report");

function targetStatus(checks) {
  const status = {};
  for (const c of checks) {
    if (c.target && (SEVERITY[c.status] ?? 0) > (SEVERITY[status[c.target]] ?? 0)) status[c.target] = c.status;
  }
  return status;
}

// ------------------------------------------------------------------ header

function titleBlock(project) {
  const cell = (k, v) => el("div", {}, el("div", { class: "k" }, k), el("div", { class: "v" }, v || "—"));
  return el("div", { class: "title-block" },
    cell("Project", project.name), cell("Element ref", project.ref), cell("Engineer", project.engineer),
    cell("Date", project.date || new Date().toISOString().slice(0, 10)),
    el("div", {}, el("div", { class: "k" }, "Element"), el("div", { class: "v" }, "Column · Ch 5")),
    el("div", { class: "basis" }, "Basis: BS EN 1992-1-1 with the UK National Annex values used in How to Design Concrete ",
      "Structures using Eurocode 2 (The Concrete Centre, 2006). Generated by EC2 Element Checker."));
}

function actions(state) {
  const pdfBtn = el("button", { class: "btn primary", type: "button" }, "⤓ Download PDF report");
  pdfBtn.addEventListener("click", async () => {
    pdfBtn.disabled = true;
    pdfBtn.textContent = "Preparing PDF…";
    try {
      const res = await fetch("/api/column/report.pdf", {
        method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(state.input),
      });
      if (!res.ok) throw new Error(String(res.status));
      const name = /filename="?([^";]+)"?/.exec(res.headers.get("Content-Disposition") || "")?.[1] || "EC2-column-check.pdf";
      downloadBlob(await res.blob(), name);
    } catch (err) {
      alert("The PDF could not be created. Is the server still running?");
    } finally {
      pdfBtn.disabled = false;
      pdfBtn.textContent = "⤓ Download PDF report";
    }
  });
  const ref = (state.result.project.ref || "column").replace(/[^A-Za-z0-9_-]+/g, "-");
  const jsonBtn = el("button", { class: "btn", type: "button" }, "Export inputs (JSON)");
  jsonBtn.addEventListener("click", () =>
    downloadBlob(new Blob([JSON.stringify(state.input, null, 2)], { type: "application/json" }), `EC2-column-${ref}.json`));
  const printBtn = el("button", { class: "btn", type: "button" }, "Print");
  printBtn.addEventListener("click", () => window.print());
  return el("div", { class: "report-actions" }, pdfBtn, printBtn, jsonBtn,
    el("a", { class: "btn", href: "/column" }, "← Edit inputs"), el("a", { class: "btn ghost", href: "/" }, "Choose another element"));
}

// ------------------------------------------------------------------ summary

function ring(summary) {
  const c = summary.counts;
  const tested = c.pass + c.fail + c.warn;
  const frac = tested ? c.pass / tested : 1;
  const r = 26, len = 2 * Math.PI * r;
  return el("div", { html: `<svg class="ring" viewBox="0 0 64 64" aria-hidden="true">
    <circle cx="32" cy="32" r="${r}" fill="none" stroke="rgba(255,255,255,.25)" stroke-width="7"/>
    <circle cx="32" cy="32" r="${r}" fill="none" stroke="#fff" stroke-width="7" stroke-linecap="round"
      stroke-dasharray="${len * frac} ${len}" transform="rotate(-90 32 32)"/>
    <text x="32" y="37" text-anchor="middle" font-size="15" font-weight="700" fill="#fff">${c.pass}/${tested}</text></svg>` });
}

function verdict(summary) {
  const c = summary.counts;
  return el("div", { class: `verdict ${summary.verdict}` }, ring(summary),
    el("div", {},
      el("div", { class: "big" }, verdictText(summary)),
      el("div", { class: "counts" },
        el("span", {}, `${c.pass} passed`), el("span", {}, `${c.fail} failed`), el("span", {}, `${c.warn} warnings`),
        el("span", {}, `${c.info} information`), el("span", {}, `${c.na} not applicable`))));
}

function groupTiles(result) {
  return el("div", { class: "group-tiles" }, result.groups.map((g, i) => {
    const items = result.checks.filter((c) => c.group === g);
    const status = worst(items.map((c) => c.status));
    return el("a", { class: `group-tile ${status}`, href: `#group-${i}` },
      el("div", { class: "name" }, `${String(i + 1).padStart(2, "0")} ${g}`),
      el("div", { class: "dots" }, items.map((c) => el("i", { class: c.status, title: `${c.title}: ${STATUS_LABEL[c.status]}` }))),
      chip(status));
  }));
}

function keyResults(result) {
  const by = Object.fromEntries(result.checks.map((c) => [c.id, c]));
  const d = result.derived;
  const tile = (label, check, value, sub) => el("div", { class: "sheet key" },
    el("div", { class: "k" }, el("span", {}, label), check ? chip(check.status) : null),
    el("div", { class: "v", html: value }),
    check && check.utilisation !== null ? utilBar(check.utilisation) : el("div", { class: "help" }, sub || ""));
  const reqs = ["y", "z"].map((a) => d.axes[a].As_req).filter((v) => v !== null);
  return el("div", { class: "key-results" },
    tile("Bending about y–y", by.bending_y, by.bending_y.markup.result),
    tile("Bending about z–z", by.bending_z, by.bending_z.markup.result),
    tile("Axial resistance", by.axial, by.axial.markup.result),
    tile("Biaxial bending", by.biaxial, by.biaxial.markup.result, by.biaxial.note),
    tile("Slenderness y–y / z–z", null,
      `λ ${fmt(d.axes.y.lam)} / ${fmt(d.axes.z.lam)}`,
      `λlim ${fmt(d.axes.y.lam_lim)} / ${fmt(d.axes.z.lam_lim)}: ${d.axes.y.slender ? "slender" : "not slender"} / ${d.axes.z.slender ? "slender" : "not slender"}`),
    tile("Reinforcement", by.as_min,
      `A<sub>s,prov</sub> ${fmt(d.As, 0)} mm²`,
      reqs.length ? `As,req ${fmt(Math.max(...reqs), 0)} mm² · ρ ${fmt(100 * d.rho, 2)} %` : "As,req not achievable"));
}

function figure(title, body, caption, extra) {
  return el("figure", { class: "sheet figure", style: "margin:0" },
    el("div", { class: "sheet-head" }, el("h3", {}, title), extra || null),
    el("div", { class: "sheet-body" }, body),
    caption ? el("figcaption", {}, caption) : null);
}

function tabs(onSelect) {
  const wrap = el("div", { class: "tabs", role: "tablist" });
  for (const axis of ["y", "z"]) {
    const b = el("button", { type: "button", role: "tab", "aria-selected": axis === "y" ? "true" : "false" }, `${axis}–${axis}`);
    b.addEventListener("click", () => {
      wrap.querySelectorAll("button").forEach((x) => x.setAttribute("aria-selected", x === b ? "true" : "false"));
      onSelect(axis);
    });
    wrap.append(b);
  }
  return wrap;
}

function figures(state) {
  const { result, input } = state;
  const status = targetStatus(result.checks);
  const sectionBox = el("div", { id: "fig-section" });
  const elevationBox = el("div");
  const nmY = el("div"), nmZ = el("div");
  const by = Object.fromEntries(result.checks.map((c) => [c.id, c]));

  const drawElev = (axis) => {
    const ax = result.derived.axes[axis];
    drawElevation(elevationBox, {
      l: result.derived.l, depth: ax.depth, NEd: result.derived.NEd, l0: ax.l0,
      ...endKinds(input.restraint[axis]),
      moments: { ...ax, axis },
    });
  };
  const grid = el("div", { class: "figure-grid" },
    figure("Cross-section", sectionBox, "Drawn to scale. A part outlined in red failed a check; hover a row of the report to locate it."),
    figure("Elevation & design moments", elevationBox, "Moment diagram after Ch 5, Fig 4: first order (dashed) and with second-order effects (solid).",
      tabs(drawElev)),
    figure("N–M interaction about y–y", nmY, "Capacity curve for the reinforcement provided (Figs 7–9). The design point must lie inside."),
    figure("N–M interaction about z–z", nmZ, ""));
  queueMicrotask(() => {
    drawSection(sectionBox, result.plots.section, { status, linkLabel: `H${input.reinforcement.link_dia} @ ${input.reinforcement.link_spacing}` });
    drawElev("y");
    drawInteraction(nmY, result.plots.interaction.y, { axis: "y", status: by.bending_y.status });
    drawInteraction(nmZ, result.plots.interaction.z, { axis: "z", status: by.bending_z.status });
  });
  return grid;
}

// ------------------------------------------------------------------ flowchart (Fig 2 / Fig 3)

function node(label, value, cls = "on") {
  return el("div", { class: `flow-node ${cls}` }, el("div", { class: "fl" }, label), el("div", { class: "fv", html: value }));
}
const arrow = (on = true) => el("div", { class: `flow-arrow${on ? " on" : ""}` });

function flow(result, axis) {
  const ax = result.derived.axes[axis];
  const by = Object.fromEntries(result.checks.map((c) => [c.id, c]));
  const bend = by[`bending_${axis}`];
  const detailing = worst(result.checks.filter((c) => c.group === "Detailing").map((c) => c.status));
  const slender = ax.slender;
  const branch = el("div", { class: "flow-branch" },
    el("div", { class: `col ${slender ? "off" : "on"}` }, el("div", { class: "tag" }, "NO"),
      node("Column is not slender", `M<sub>Ed</sub> = M<sub>02</sub> = ${fmt(ax.M02)} kNm`, slender ? "off" : "on")),
    el("div", { class: `col ${slender ? "on" : "off"}` }, el("div", { class: "tag" }, "YES · Fig 3"),
      node("Nominal curvature", slender
        ? `K<sub>r</sub> = ${fmt(ax.Kr, 3)}, K<sub>φ</sub> = ${fmt(ax.Kphi, 3)}<br>e<sub>2</sub> = ${fmt(ax.e2)} mm, M<sub>2</sub> = ${fmt(ax.M2)} kNm<br>M<sub>Ed</sub> = ${fmt(ax.MEd)} kNm`
        : "not required", slender ? "on" : "off")));
  return el("div", { class: "flow" },
    node("Start: actions on the column", `N<sub>Ed</sub> = ${fmt(result.derived.NEd, 0)} kN · M<sub>top</sub> = ${fmt(ax.M_top)} · M<sub>bottom</sub> = ${fmt(ax.M_bottom)} kNm`),
    arrow(),
    node("Effective length (Fig 5 / Table 4)", `l<sub>0</sub> = ${fmt(ax.F, 3)} × ${fmt(result.derived.l / 1000, 2)} m = ${fmt(ax.l0 / 1000, 2)} m`),
    arrow(),
    node("First-order moments", `e<sub>i</sub> = ${fmt(ax.e_i)} mm · M<sub>01</sub> = ${fmt(ax.M01)} · M<sub>02</sub> = ${fmt(ax.M02)} kNm`),
    arrow(),
    node("Slenderness", `λ = 3.46·l<sub>0</sub>/${axis === "y" ? "h" : "b"} = ${fmt(ax.lam)} · λ<sub>lim</sub> = 20ABC/√n = ${fmt(ax.lam_lim)}`),
    arrow(),
    el("div", { class: "flow-diamond" }, el("span", { html: `Is λ ≥ λ<sub>lim</sub>?  ${slender ? "YES" : "NO"}` })),
    arrow(),
    branch,
    arrow(),
    node("Resistance (Figs 7–9)", `${bend.markup.result}<br>A<sub>s,req</sub> = ${ax.As_req === null ? "—" : fmt(ax.As_req, 0)} mm² · A<sub>s,prov</sub> = ${fmt(result.derived.As, 0)} mm²`, bend.status),
    arrow(),
    node("Detailing rules (spacing & quantity)", `${STATUS_LABEL[detailing]}: bar size, A<sub>s,min</sub>, A<sub>s,max</sub>, spacing, links`, detailing === "fail" ? "fail" : "pass"));
}

function flowSection(result) {
  const box = el("div");
  const draw = (axis) => box.replaceChildren(flow(result, axis));
  draw("y");
  return el("section", { class: "sheet", style: "margin-top:16px" },
    el("div", { class: "sheet-head" }, el("h3", {}, "Design flow: path taken through Ch 5, Figs 2 and 3"), tabs(draw)),
    el("div", { class: "sheet-body" }, box));
}

// ------------------------------------------------------------------ full report

function refCell(refs) {
  return el("td", { class: "ref" }, refs.map((r) => r.page
    ? el("a", { href: guideHref(r.page), target: "_blank", rel: "noopener" }, r.label, " ", el("span", { class: "pg" }, `p.${r.page}`))
    : el("div", { class: "pg" }, r.label)));
}

function calcGroups(result) {
  return result.groups.map((group, gi) => {
    const items = result.checks.filter((c) => c.group === group);
    if (!items.length) return null;
    const rows = items.map((c) => {
      const row = el("tr", { "data-target": c.target || "" },
        refCell(c.refs),
        el("td", {}, el("div", { class: "ct" }, c.title),
          ...c.markup.working.map((w) => el("div", { class: "wl", html: w })),
          c.note ? el("div", { class: "note", html: `Note: ${c.markup.note}` }) : null),
        el("td", { class: "out" }, el("div", { class: "res", html: c.markup.result }), chip(c.status),
          c.utilisation !== null ? el("div", { style: "margin-top:8px" }, utilBar(c.utilisation)) : null));
      row.addEventListener("mouseenter", () => highlight(c.target, true));
      row.addEventListener("mouseleave", () => highlight(c.target, false));
      return row;
    });
    const status = worst(items.map((c) => c.status));
    return el("div", { class: "calc-group", id: `group-${gi}` },
      el("h3", {}, `${String(gi + 1).padStart(2, "0")} · ${group}`, chip(status)),
      el("div", { class: "sheet", style: "overflow:hidden" },
        el("table", { class: "calc" },
          el("thead", {}, el("tr", {}, el("th", {}, "Ref"), el("th", {}, "Calculation"), el("th", {}, "Output"))),
          el("tbody", {}, rows))));
  });
}

function highlight(target, on) {
  if (!target) return;
  document.querySelectorAll(`#fig-section [data-part="${target}"]`).forEach((n) => n.classList.toggle("is-hl", on));
}

function inputsTable(result) {
  return el("div", { class: "sheet", style: "margin-top:12px" },
    el("table", { class: "kv" }, el("tbody", {}, result.inputs.map((i) =>
      el("tr", {}, el("td", {}, i.label), el("td", { class: "num" }, i.value))))));
}

function render(state) {
  const { result } = state;
  document.title = `Column ${result.project.ref || ""} · EC2 Report`.replace("  ", " ");
  root.replaceChildren(
    el("div", { class: "eyebrow" }, "Results · Column (pillar)"),
    el("h1", { class: "title" }, "Column check report"),
    titleBlock(result.project),
    actions(state),
    el("h2", { class: "section-title" }, el("span", { class: "idx" }, "01"), "Overall summary"),
    verdict(result.summary),
    groupTiles(result),
    keyResults(result),
    figures(state),
    flowSection(result),
    el("h2", { class: "section-title" }, el("span", { class: "idx" }, "02"), "Full report: calculations"),
    el("p", { class: "lede", style: "font-size:13.5px" },
      "Every test with its working, the result and the reference to the guide. Click a reference to open the guide at that page."),
    ...calcGroups(result).filter(Boolean),
    el("h2", { class: "section-title" }, el("span", { class: "idx" }, "03"), "Inputs"),
    inputsTable(result),
    el("h2", { class: "section-title" }, el("span", { class: "idx" }, "04"), "Assumptions"),
    el("div", { class: "sheet sheet-body" }, el("ul", { class: "assumptions" }, result.assumptions.map((a) => el("li", {}, a)))),
    el("p", { class: "notice" }, "For learning and preliminary checking. A qualified structural engineer must verify the inputs and results."));
}

const state = store.getSession(KEYS.result);
if (!state?.result) {
  root.replaceChildren(el("div", { class: "empty" }, "No results yet. ", el("a", { href: "/column" }, "Enter a column to check →")));
} else {
  render(state);
  if (location.hash) document.querySelector(location.hash)?.scrollIntoView();
}
